let currentLang = 'gu';
try {
    const saved = localStorage.getItem('solarflow_language');
    if (saved && (saved === 'gu' || saved === 'en')) {
        currentLang = saved;
    }
} catch (_) {}

export function getLanguage() {
    return currentLang;
}

export function setLanguage(lang) {
    if (lang === 'gu' || lang === 'en') {
        currentLang = lang;
        try {
            localStorage.setItem('solarflow_language', lang);
            window.dispatchEvent(new CustomEvent('solarflow_language_change', { detail: lang }));
        } catch (_) {}
    }
}

export function t(key, fallback = null) {
    const langDict = translations[currentLang] || translations.gu;
    if (langDict[key] !== undefined) return langDict[key];
    if (translations.en[key] !== undefined) return translations.en[key];
    return fallback !== null ? fallback : key;
}

export function getMonthName(monthIndex) {
    const langDict = translations[currentLang] || translations.gu;
    return langDict.months[monthIndex % 12] || '';
}

export function getDayShort(dayIndex) {
    const langDict = translations[currentLang] || translations.gu;
    return langDict.daysShort[dayIndex % 7] || '';
}
